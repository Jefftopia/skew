/**
 * v1 mobile client reading portfolio-fund from an API that now serves v2.
 *
 * The client was built and shipped against schema version 1:
 *
 *   { id, name, currency, cashPct, navPerShare, asOf }
 *
 * The server now responds with version 2 bodies:
 *
 *   { id, name, baseCurrency, liquidity: { cashPct, hqlaPct }, navPerShare, asOf }
 *
 * A plain v1 reader would see `currency === undefined` and `cashPct === undefined`
 * and break. With @braid/contract the read comes back as status "ahead"
 * (payload version 2 > highest version this build knows, which is 1); the
 * contract resolver cures that by fetching the origin's contract document from
 * /.well-known/skew/contracts/portfolio-fund and running the 2 -> 1 lens
 * DOWN over the body:
 *
 *   baseCurrency        -> currency            (rename inverted, lossless)
 *   liquidity.cashPct   -> cashPct             (move inverted, lossless)
 *   liquidity.hqlaPct   -> DROPPED             (v1 has nowhere to put it: LOSSY)
 */
import { registerSchema, envelopeFromResponse } from '@braid/skew';
import { versionedFromContract, createContractResolver } from '@braid/contract';

// ---------------------------------------------------------------------------
// The shape this build of the app actually understands (v1).
// ---------------------------------------------------------------------------
export interface PortfolioFundV1 {
  id: string;
  name: string;
  currency: string;
  cashPct: number;
  navPerShare: number;
  asOf: string;
}

// The contract snapshot baked into the app at build time (generated by
// `skew-contract gen` when the app was last released — it only knows v1).
import * as pinnedContract from './portfolio-fund.contract.v1-snapshot.json';

// Register the versioned type from the pinned contract. This build's highest
// known version is 1, so any v2 envelope will read as "ahead".
const portfolioFund = versionedFromContract<PortfolioFundV1>(pinnedContract, {
  pinned: 1,
});
registerSchema(portfolioFund);

// A resolver that knows how to cure "ahead": it fetches the ORIGIN's current
// contract document (which does know v2 and carries the 1<->2 lens) and uses
// the down direction of that lens to rewrite the body into the pinned shape.
const resolver = createContractResolver({
  fetch: (url, init) => fetch(url, init),
  // Contract documents are small and cache-friendly (ETag + max-age on the
  // server); memoize per app session so we hit the network once.
  cache: 'memory',
});

// ---------------------------------------------------------------------------
// The actual fetch path the v1 app uses.
// ---------------------------------------------------------------------------
export async function loadFund(fundId: string): Promise<PortfolioFundV1> {
  const res = await fetch(`https://api.example.com/funds/${fundId}`);
  if (!res.ok) throw new Error(`funds API returned ${res.status}`);

  // Pull the skew envelope (name + version) off the response — version may
  // travel in the body envelope or in HTTP headers; this handles both.
  const envelope = await envelopeFromResponse(res);

  // readResolving:
  //  - version <= 1  -> reads locally with the pinned contract (no network)
  //  - version 2     -> status "ahead" -> fetches
  //                     https://api.example.com/.well-known/skew/contracts/portfolio-fund
  //                     and applies the 2 -> 1 lens down over the body
  const result = await resolver.readResolving(portfolioFund, envelope);

  if (!result.ok) {
    // Only unreachable-contract / no-down-path cases land here; surface them
    // rather than handing garbage to the UI.
    throw new Error(`portfolio-fund read failed: ${result.error}`);
  }

  if (result.downgradedFrom !== undefined) {
    // ------------------------------------------------------------------
    // WHAT THIS v1 CLIENT LOSES when the body was downgraded from v2:
    //
    //   result.lossyPaths === ['liquidity.hqlaPct']
    //
    //   - liquidity.hqlaPct  — the new high-quality-liquid-assets metric.
    //     v1 has no field for it, so the down lens drops it. The app cannot
    //     display an HQLA figure until it upgrades to the v2 contract.
    //
    // NOT lost (structurally rewritten, values intact):
    //   - baseCurrency  -> arrives as `currency`
    //   - liquidity.cashPct -> arrives as flat `cashPct`
    // ------------------------------------------------------------------
    console.info(
      `portfolio-fund ${fundId}: downgraded v${result.downgradedFrom} -> v1;` +
        ` dropped: ${result.lossyPaths.join(', ')}`,
    );
  }

  // Typed as the v1 shape the rest of the app was compiled against.
  return result.value;
}
