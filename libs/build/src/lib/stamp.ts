import { execSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';

/**
 * Build identity, and the manifest an origin serves so clients can discover it.
 *
 * Identity is generated as a *file*, not a bundler `define`. That keeps it
 * portable across Angular CLI, Vite, and webpack, and — more usefully — makes
 * it readable in tests and Node without running a build at all.
 */

export interface StampOptions {
  /** Where to write the generated TypeScript constants. */
  readonly out: string;
  /** Where to write the JSON manifest the origin will serve. */
  readonly manifest?: string;
  /**
   * Directory to scan for emitted chunks. Present, the manifest gains a
   * `modules` map, which is what lets a client distinguish "this route moved"
   * from "this route was deleted".
   */
  readonly assetDir?: string;
  /** Overrides the derived id. CI should pass its commit SHA. */
  readonly buildId?: string;
  /** Overrides the timestamp. Mainly for reproducible tests. */
  readonly builtAt?: string;
  readonly cwd?: string;
}

export interface StampResult {
  readonly buildId: string;
  readonly builtAt: string;
  readonly modules: Record<string, { file: string; hash?: string }>;
}

/**
 * Resolves a build id.
 *
 * Order matters: an explicit id wins, then CI's `SKEW_BUILD_ID`, then the git
 * SHA (stable, meaningful, and identical across parallel CI jobs building the
 * same commit), then a random value as a last resort.
 *
 * The random fallback is deliberately *not* a content hash of the output —
 * two machines building the same commit should agree, and a content hash of a
 * directory containing timestamps would not.
 */
export function resolveBuildId(explicit?: string, cwd = process.cwd()): string {
  if (explicit) return explicit;
  const fromEnv = process.env['SKEW_BUILD_ID'];
  if (fromEnv) return fromEnv;
  try {
    return execSync('git rev-parse --short HEAD', {
      cwd,
      stdio: ['ignore', 'pipe', 'ignore'],
      encoding: 'utf8',
    }).trim();
  } catch {
    return createHash('sha256').update(String(Date.now())).digest('hex').slice(0, 10);
  }
}

/**
 * Scans an output directory for JavaScript chunks.
 *
 * Best-effort by design. Without a bundler metafile there is no way to recover
 * the *logical* module a chunk came from, so entries are keyed by their
 * emitted basename. Consumers that need logical ids supply them explicitly at
 * the call site (see `lazy()` in `@braidlabs/angular-router`).
 */
export function scanAssets(assetDir: string): Record<string, { file: string; hash?: string }> {
  const modules: Record<string, { file: string; hash?: string }> = {};
  let entries: string[];
  try {
    entries = walk(assetDir);
  } catch {
    return modules;
  }
  for (const abs of entries) {
    if (!abs.endsWith('.js') && !abs.endsWith('.mjs')) continue;
    const file = relative(assetDir, abs).split(sep).join('/');
    // "chunk-ABC123.js" and "main-XYZ.js" → logical key without the hash
    const base = file.replace(/^.*\//, '');
    const key = base.replace(/[.-][A-Za-z0-9_]{6,}\.m?js$/, '').replace(/\.m?js$/, '');
    modules[key] = { file };
  }
  return modules;
}

function walk(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const abs = join(dir, name);
    if (statSync(abs).isDirectory()) out.push(...walk(abs));
    else out.push(abs);
  }
  return out;
}

/** Generates the identity module and, optionally, the manifest. */
export function stamp(options: StampOptions): StampResult {
  const cwd = options.cwd ?? process.cwd();
  const buildId = resolveBuildId(options.buildId, cwd);
  const builtAt = options.builtAt ?? new Date().toISOString();
  const modules = options.assetDir ? scanAssets(join(cwd, options.assetDir)) : {};

  const source = `// Generated by @braidlabs/build — do not edit.
// Regenerated on every build; safe to gitignore.
export const BUILD_ID = ${JSON.stringify(buildId)};
export const BUILT_AT = ${JSON.stringify(builtAt)};
export const BUILD_IDENTITY = { buildId: BUILD_ID, builtAt: BUILT_AT } as const;
`;
  writeFileTree(join(cwd, options.out), source);

  if (options.manifest) {
    const manifest = {
      buildId,
      builtAt,
      ...(Object.keys(modules).length > 0 ? { modules } : {}),
    };
    writeFileTree(join(cwd, options.manifest), JSON.stringify(manifest, null, 2) + '\n');
  }

  return { buildId, builtAt, modules };
}

function writeFileTree(path: string, contents: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, contents, 'utf8');
}
